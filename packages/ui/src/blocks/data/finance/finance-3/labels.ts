export function resolveFinance3Labels(
  labels: Finance3LabelsOverride | undefined,
): Finance3Labels {
  const base = defaultFinance3Labels
  const entries = labels?.entries
  const receivables = labels?.receivables
  const statement = labels?.statement
  const clientMoney = labels?.clientMoney
  return {
    ...base,
    ...labels,
    clientMoney: {
      ...base.clientMoney,
      ...clientMoney,
      columns: { ...base.clientMoney.columns, ...clientMoney?.columns },
    },
    entries: {
      ...base.entries,
      ...entries,
      columns: { ...base.entries.columns, ...entries?.columns },
      feeTypes: { ...base.entries.feeTypes, ...entries?.feeTypes },
      kinds: { ...base.entries.kinds, ...entries?.kinds },
      situations: { ...base.entries.situations, ...entries?.situations },
      types: { ...base.entries.types, ...entries?.types },
    },
    paginationButtons: {
      ...base.paginationButtons,
      ...labels?.paginationButtons,
    },
    receivables: {
      ...base.receivables,
      ...receivables,
      chargeStatuses: {
        ...base.receivables.chargeStatuses,
        ...receivables?.chargeStatuses,
      },
      columns: { ...base.receivables.columns, ...receivables?.columns },
    },
    savedViews: { ...base.savedViews, ...labels?.savedViews },
    statement: {
      ...base.statement,
      ...statement,
      columns: { ...base.statement.columns, ...statement?.columns },
      kinds: { ...base.statement.kinds, ...statement?.kinds },
    },
    views: { ...base.views, ...labels?.views },
  }
}
