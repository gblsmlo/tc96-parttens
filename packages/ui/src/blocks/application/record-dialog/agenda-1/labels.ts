export function resolveAgenda1Labels(
  labels: Partial<Agenda1Labels> | undefined,
): Agenda1Labels {
  const base = defaultAgenda1Labels
  return {
    ...base,
    ...labels,
    peoplePicker: { ...base.peoplePicker, ...labels?.peoplePicker },
    schedule: { ...base.schedule, ...labels?.schedule },
    text: { ...base.text, ...labels?.text },
  }
}
