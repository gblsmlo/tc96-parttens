import { readFile, writeFile } from 'node:fs/promises'
import { defaultPreset, presets, presetsCss } from '../src'

const target = 'apps/example/packages/ui/src/themes/presets.css'
const check = process.argv.includes('--check')

const generated = `/* Generated by \`bun run themes:build\` from packages/themes/src/presets. Do not edit. */\n\n${presetsCss(presets, defaultPreset)}\n`
const format = Bun.spawnSync(
  ['bunx', 'biome', 'format', `--stdin-file-path=${target}`],
  { stdin: new TextEncoder().encode(generated) },
)
if (format.exitCode !== 0) throw new Error(format.stderr.toString())
const css = format.stdout.toString()

if (check) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== css)
    throw new Error(`${target} is out of date; run bun run themes:build.`)
  console.log(`${target} matches the ${presets.length} presets.`)
} else {
  await writeFile(target, css)
  console.log(`Wrote ${presets.length} presets to ${target}.`)
}
