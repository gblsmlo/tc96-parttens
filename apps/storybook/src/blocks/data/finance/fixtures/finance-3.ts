const isIncome = (item: Finance3Entry) =>
  item.kind === 'fee' || item.kind === 'other_income'
const isUnsettled = (item: Finance3Entry) =>
  item.situation === 'open' || item.situation === 'overdue'

export const entryInView = (item: Finance3Entry, view: Finance3View) => {
  if (view === 'receivable') return isIncome(item) && isUnsettled(item)
  if (view === 'payable') return item.kind === 'expense' && isUnsettled(item)
  if (view === 'settled') return item.situation === 'settled'
  return true
}

