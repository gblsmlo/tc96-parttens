export const summarize = (
  list: readonly Revenue3Account[],
): Revenue3Summary => {
  const totalArr = list.reduce((sum, item) => sum + item.arr, 0)
  const weighted = list.reduce((sum, item) => sum + item.arr * item.nrr, 0)
  return {
    atRiskArr: list
      .filter((item) => item.health === 'atRisk')
      .reduce((sum, item) => sum + item.arr, 0),
    portfolioNrr: totalArr > 0 ? weighted / totalArr : 1,
    totalArr,
  }
}

