import { writeFile } from 'node:fs/promises'
import {
  basePresets,
  googleFontsHref,
  presetCss,
  presetsModule,
  sharedTokens,
  type ThemePreset,
  type TweakcnItem,
  tweakcnRegistry,
  webFonts,
} from './theme-presets'

// Writes the tweakcn presets into the example theme as `data-theme-preset`
// rules, and the list of every preset the theme ships. Base colors are
// hand-written in themes/base-colors.css and only listed here.
const themesDirectory = 'apps/example/packages/ui/src/themes'

const response = await fetch(tweakcnRegistry)
if (!response.ok)
  throw new Error(`${tweakcnRegistry} answered ${response.status}`)
const { items } = (await response.json()) as { items: TweakcnItem[] }

const googleFonts = new Map<string, boolean>()
const onGoogleFonts = async (family: string) => {
  const known = googleFonts.get(family)
  if (known !== undefined) return known
  const found = (await fetch(googleFontsHref([family]))).ok
  googleFonts.set(family, found)
  return found
}

const sorted = [...items].sort((a, b) =>
  (a.title ?? a.name).localeCompare(b.title ?? b.name),
)
const presets: ThemePreset[] = [...basePresets]
for (const item of sorted) {
  const fonts: string[] = []
  for (const family of webFonts(sharedTokens(item)))
    if (await onGoogleFonts(family)) fonts.push(family)
  presets.push({
    value: item.name,
    title: item.title ?? item.name,
    source: 'tweakcn',
    ...(fonts.length ? { fontsHref: googleFontsHref(fonts) } : {}),
  })
}

const css = `/* Generated by \`bun run sync:themes\` from ${tweakcnRegistry} (tweakcn, Apache-2.0). Do not edit. */\n\n${sorted.map(presetCss).join('\n\n')}\n`
await writeFile(`${themesDirectory}/tweakcn.css`, css)
await writeFile(`${themesDirectory}/presets.ts`, presetsModule(presets))

const format = Bun.spawnSync([
  'bunx',
  'biome',
  'format',
  '--write',
  `${themesDirectory}/tweakcn.css`,
  `${themesDirectory}/presets.ts`,
])
if (format.exitCode !== 0) throw new Error(format.stderr.toString())

const missing = [...googleFonts].filter(([, found]) => !found)
console.log(
  `Synced ${sorted.length} tweakcn presets.${missing.length ? ` Not on Google Fonts: ${missing.map(([family]) => family).join(', ')}` : ''}`,
)
